import { Avatar, Style } from "@dicebear/core";
import croodlesNeutralDefinition from "@dicebear/styles/croodles-neutral.json" with { type: "json" };
import { doodleForIndex } from "./catalog.js";
import { normalizeCoachConfig } from "./state.js";

const croodlesNeutral = new Style(croodlesNeutralDefinition);

export function renderCoachSvg(input, { title = "SpeakUp profile doodle" } = {}) {
  const config = normalizeCoachConfig(input);
  const doodle = doodleForIndex(config.doodle);
  const svg = new Avatar(croodlesNeutral, {
    seed: `speakup-croodles-${doodle.index}`,
    size: 256,
    idRandomization: true,
    eyesVariant: [doodle.eyes],
    mouthVariant: [doodle.mouth],
    noseVariant: [doodle.nose],
    backgroundColor: ["#fffdf7"],
    inkColor: ["#141b2b"]
  }).toString();
  const accessibleTitle = escapeXml(title);
  return svg
    .replace('aria-hidden="true"', `role="img" aria-label="${accessibleTitle}"`)
    .replace("<!-- Generated by DiceBear (https://www.dicebear.com) -->", `<title>${accessibleTitle}</title>`);
}

export function coachSvgDataUri(config, { title = "" } = {}) {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(renderCoachSvg(config, { title }))}`;
}

function escapeXml(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[char]);
}
